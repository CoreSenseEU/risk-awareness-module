"""
run_experiments.py

Runs experiments on a dataset (and run if applicable) and evaluates the results.
"""

import argparse
from pathlib import Path
import sys

sys.path.append(str(Path(__file__).parent.parent))

# pylint: disable=wrong-import-position
from riskam.data.ml_datasets import DATASETS
from riskam.experiments import inspect_predictions, run_experiments
from riskam.sweep_config import load_sweep_config


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Run experiments on a dataset")
    parser.add_argument(
        "action", type=str, choices=["run", "inspect"], help="The dataset to process."
    )
    parser.add_argument(
        "dataset", type=str, choices=DATASETS.keys(), help="The dataset to process."
    )
    parser.add_argument(
        "--run",
        type=str,
        choices=[f"RB_0{i}" for i in range(1, 9)],
        help="The run to process",
    )
    parser.add_argument(
        "--pred",
        type=str,
        choices=["correct", "underestimate", "overestimate"],
        help="The prediction type to inspect.",
    )
    parser.add_argument(
        "--split",
        type=str,
        choices=["val", "test"],
        default=None,
        help=(
            "Restrict to one bucket of the canonical val/test split "
            "(generated by scripts/generate_split.py). Sweep tuning should "
            "use 'val'; the final paper number is reported on 'test' once."
        ),
    )
    parser.add_argument(
        "--sweep-config",
        type=Path,
        default=None,
        help=(
            "Path to a YAML sweep config. If omitted, "
            "configs/sweeps/default.yaml is loaded."
        ),
    )
    args = parser.parse_args()

    if args.action == "inspect":
        inspect_predictions(args.dataset, args.pred, args.run, split=args.split)
    elif args.action == "run":
        sweep = load_sweep_config(args.sweep_config) if args.sweep_config else None
        run_experiments(
            args.dataset,
            args.run,
            split=args.split,
            sweep_config=sweep,
        )
